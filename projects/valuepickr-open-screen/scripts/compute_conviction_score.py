#!/usr/bin/env python3
"""
Computes a mechanical, deterministic 0-100 "conviction_score" for every researched
stock in state.json, WITHOUT touching the existing categorical `conviction` field.

WHY THIS EXISTS
----------------
The categorical `conviction` field (Low/Low-Medium/Medium/Medium-High/High) is
pure per-stock LLM re-derivation every research run, with nothing mechanical to
check consistency against past calls. This has already caused two observed bugs:
(1) the same underlying situation - small-cap, weak trailing-average ROE, real
recent-quarter inflection - got classified differently across two different
stocks in two different runs; (2) an explicit "very-high trusted + no red flag
=> at least Medium-High" rule (see audit_state.py section 3.5) was violated
twice within the same session it was written, because there was no mechanical
scoring layer to check the LLM's output against.

`conviction_score` is a pure function of fields already sitting in state.json
(and trusted_users.json / a stock's own data/<slug>.json). It never calls an
LLM and never touches the network, so given the same state.json it always
produces the same number - useful as a cross-check against the categorical
field, and as a ranking signal that isn't subject to per-run drift.

FORMULA (see component docstrings below)
----------------------------------------------------------------------------------
  own_conviction = base_anchor          (0-44,  regraded categorical `conviction`)
                 + thesis_bonus         (0-20,  from `thesis_fit`)
                 + quality_lift         (-8..+10, from this stock's OWN quality_score)
                 + management_component (-12..+12, from data/<slug>.json `management_quality`)
                 - red_flag_penalty     (0 or 25, or forces the whole score to 0)

  trusted_lift   = trusted_signal_component            (-20..+24, SIGNED trusted-thread ledger)
                   but if negative, floored at -0.5 * max(own_conviction, 0)
                   -- one trusted user souring/exiting can HALVE the standalone
                      thesis at worst, never invert it.

  conviction_score = clamp(own_conviction + trusted_lift, 0, 100)
                     [forced to 0 for AVOID/EXCLUDE red_flag_tier regardless]

WHY THE own_conviction / trusted_lift SPLIT (2026-09-10, user-requested)
----------------------------------------------------------------------
"There should be a baseline conviction score for each stock generated by your
own analysis too, before topping it up with conviction from other trusted
users. There could be stocks that are good but no one else has understood but
you." Before this, `conviction_score` for a stock with no trusted signals was
just `base_anchor + thesis_bonus` (categorical label + thesis magnitude) - and
that was true for 43% of researched stocks. `own_conviction` now also carries a
`quality_lift` term straight off the stock's own mechanical `quality_score`
(ROCE/debt/FCF/margin/capex), so a genuinely high-quality business scores well
on its own merit with zero forum corroboration. The breakdown reports
`own_conviction` and `trusted_lift` as separate line items so it's always
visible how much of a name's conviction is standalone vs borrowed.

`quality_lift` DOES overlap `quality_score`'s own 0.25 weight in master_score,
but only mildly: it's ±8..10 on a 0-100 conviction_score that is itself 0.25 of
master_score, i.e. ~2-3 effective master-score points. Deliberate and bounded -
a great business SHOULD read as both "high quality" and "high own-conviction".

Max own_conviction is 44+20+10+12 = 86; + trusted_lift 24 -> clamp 100.

TRUSTED_SIGNAL_COMPONENT (redesigned 2026-09-10)
-----------------------------------------------
Replaces the old `trust_component` (0-25, read only the single
`trusted_conviction_strength`/`_source_user` scalars on the state entry) +
`corroboration_bonus` (0-15, a flat cliff at 2 / 3+ distinct users). Those two
had three flaws the user called out: (a) they only ever ADDED - an exit or a
year-old call could never pull a score DOWN; (b) the flat corroboration cliff
plus the SKILL's separate "+1 categorical notch per qualifying mention" meant
N trusted users mentioning a stock once each could ratchet the score up almost
without bound; (c) recency was a 0.15 pass/fail gate, not a continuous decay.

The new component reads data/<slug>.json `trusted_signals[]` as the whole
ledger and is a pure function of it:

  per signal:
    w      = recency_weight.weight_for_date(signal.date)   # 1.0 / 0.6 / 0.25 / 0.05
    smult  = {very-high: 1.0, high: 0.5, else: 0.4}[signal.strength]
    tmult  = {core: 1.0, elevated: 0.5, unknown: 0.45}[trust_tier(signal.username)]
    superseded (and not an exit)          -> contributes 0 (replaced by a newer entry)
    signal_type in (exit, sell, sold)     -> NEGATIVE: TS_EXIT_BASE * smult * tmult * w
    signal_type in (trim, reduce)         -> NEGATIVE: TS_EXIT_BASE * TS_TRIM_FACTOR * smult * tmult * w
    otherwise (conviction / add / reiterate / None)
                                          -> POSITIVE: TS_POS_BASE * smult * tmult * w

  positives: sort desc, sum with GEOMETRIC diminishing returns
             pos = Σ c_i * TS_DIMINISH**i     (1st mention full, 2nd *0.55, 3rd *0.30 ...)
             so the marginal value of the 4th distinct trusted voice is < 2 pts.
  negatives: summed LINEARLY (exits stack), magnitude capped at TS_NEG_CAP.
  component = clamp(pos_capped - neg_capped, -TS_NEG_CAP, TS_POS_CAP)

Fallback: 71 older `source: "trusted-thread"` entries carry a
`trusted_conviction_strength` scalar on state but have NO ledger file yet
(written by `vpscreen-scan`, a different task/convention). For those, one
synthetic positive is added, recency-approximated from
`trusted_conviction_floor_active` (True -> 0.6, False -> 0.25, absent -> 0.4),
so removing the old scalar path doesn't silently zero them out - but a real
dated ledger entry is always worth more than the fallback.

Consequences that are INTENDED, not bugs:
  * a stock a trusted user tried and then EXITED can score below an untouched
    peer (fresh core exit ~ -9), and that penalty then decays with the exit
    post's age just like a positive call does.
  * a `very-high` tag with no forum re-touch for a year fades toward ~0 on its
    own, every run, with no audit needed.
  * the categorical `conviction` label is NO LONGER notched by trusted
    mentions at all (SKILL Step 3.3 rewritten). The only mechanical categorical
    floor is audit_state.py 3.5 (core-tier + recent + very-high + no red flag
    => >= Medium-High), which is unchanged and still feeds base_anchor here. `management_component` is TVGP's "P" (promoter/management
quality as a POSITIVE attribute, not just red-flag absence - see
playbook/ishmohit-soic-style.md); it is GUARDED - exactly 0 whenever a stock's
data file has no `management_quality` block, so it is a strict no-op on the
whole registry until `deepdive-top100` starts populating that block. In
practice almost nothing hits the ceiling, which is fine for a ranking signal
(relative ordering matters more than absolute calibration).

USAGE
-----
    python3 compute_conviction_score.py        (from scripts/ or project root)

Writes:
  - state.json:  adds/overwrites `conviction_score` on every stock entry that
    has status in ("researched", "excluded", "avoid") - i.e. has actually been
    through research, not a bare "candidate". Leaves `conviction` untouched.
    Candidates (no research done yet) are left without a conviction_score key
    entirely, since there is nothing to score.
  - data/conviction-scores.json: sorted (descending) ranked report list.

NOTE ON A CONCURRENT AGENT'S WORK
----------------------------------
Another agent is (or may be, depending on timing) landing a shared
`scripts/recency_weight.py` module (function `weight_for_date(date_str,
today=None) -> float`) and a `trusted_conviction_floor_active` field on stock
entries, plus a `trust_tier` field ("core"/"elevated") on trusted_users.json
entries. This script:
  - imports `recency_weight.weight_for_date` if the module exists;
  - otherwise falls back to an inline implementation with the identical
    signature (see `_fallback_weight_for_date` below), which should be
    DELETED and replaced with the real import once scripts/recency_weight.py
    lands for real - it's a heuristic stand-in, not a permanent fixture.
  - already found `trust_tier` present on trusted_users.json (see component 4).
  - did NOT find `trusted_conviction_floor_active` or
    `trusted_conviction_source_user` present on any state.json stock entry as
    of this run - both are handled defensively (treated as absent -> neutral/
    full-weight default) so this script keeps working once they do land.
"""
